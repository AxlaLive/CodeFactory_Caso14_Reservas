CREATE TABLE historias_clinicas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    profesional_id BIGINT NOT NULL,
    cita_id BIGINT NOT NULL,
    evolucion VARCHAR(4000) NOT NULL,
    diagnostico VARCHAR(4000) NOT NULL,
    tratamiento VARCHAR(4000) NOT NULL,
    recomendaciones VARCHAR(4000) NOT NULL,
    creado_en TIMESTAMP NOT NULL,
    CONSTRAINT fk_historias_paciente
        FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
    CONSTRAINT fk_historias_profesional
        FOREIGN KEY (profesional_id) REFERENCES profesionales (id),
    CONSTRAINT fk_historias_cita
        FOREIGN KEY (cita_id) REFERENCES citas (id)
);

CREATE INDEX idx_historias_paciente_creado
    ON historias_clinicas (paciente_id, creado_en);
