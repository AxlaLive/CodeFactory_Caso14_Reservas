CREATE TABLE profesionales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    documento VARCHAR(20) NOT NULL UNIQUE,
    especialidad VARCHAR(100) NOT NULL,
    correo VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL, -- Nuevo campo para el login
    activo BOOLEAN NOT NULL
);

CREATE TABLE espacios_fisicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    tipo VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL
);

CREATE TABLE pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    documento VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL
);

CREATE TABLE servicios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    duracion_minutos INTEGER NOT NULL
);

CREATE TABLE citas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    profesional_id BIGINT NOT NULL,
    espacio_id BIGINT NOT NULL,
    paciente_id BIGINT NOT NULL,
    servicio_id BIGINT NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    estado VARCHAR(255) NOT NULL,
    CONSTRAINT fk_citas_profesional
        FOREIGN KEY (profesional_id) REFERENCES profesionales (id),
    CONSTRAINT fk_citas_espacio
        FOREIGN KEY (espacio_id) REFERENCES espacios_fisicos (id),
    CONSTRAINT fk_citas_paciente
        FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
    CONSTRAINT fk_citas_servicio
        FOREIGN KEY (servicio_id) REFERENCES servicios (id)
);

CREATE TABLE disponibilidades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profesional_id BIGINT NOT NULL,
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    motivo VARCHAR(200),
    CONSTRAINT fk_disponibilidades_profesional
        FOREIGN KEY (profesional_id) REFERENCES profesionales (id)
);

CREATE INDEX idx_citas_fecha_profesional
    ON citas (fecha, profesional_id);

CREATE INDEX idx_citas_fecha_espacio
    ON citas (fecha, espacio_id);

CREATE INDEX idx_disponibilidades_profesional_fecha_hora
    ON disponibilidades (profesional_id, fecha, hora_inicio, hora_fin);
